// Synthetic catalog only, in memory, with the same PGlite setup as inventory
// tests. No migration sources, environment files, CLI imports or external DBs.
vi.mock("postgres", () => { throw new Error("External database clients are forbidden in catalog tests."); });
let db: PGlite;

type Grant = { grantor: string; grantee: string; privilege: string; grantable: boolean };
type Named = { name: string };
type Relation = Named & {
  kind: string; owner: string; acl: Grant[]; rls: boolean; partition: boolean; partitionBound: string | null; parents: string[];
  view: string | null; options: string[];
  columns: (Named & { acl: Grant[]; identity: string; generated: string; default: string | null })[];
  indexes: (Named & { definition: string; valid: boolean })[];
  constraints: (Named & { definition: string; type: string })[];
  triggers: (Named & { internal: boolean; definition: string })[];
  policies: (Named & { using: string | null; check: string | null; roles: string[] })[];
};
type Metadata = {
  schema: Named & { owner: string; acl: Grant[] };
  relations: Relation[];
  types: (Named & { kind: string; owner: string; acl: Grant[]; labels: string[] | null; notNull: boolean; default: string | null })[];
  routines: (Named & { kind: string; arguments: string; result: string | null; acl: Grant[] })[];
  defaultPrivileges: { role: string; namespace: string; type: string; acl: Grant[] }[];
};

function named<T extends Named>(entries: T[], name: string): T {
  const entry = entries.find((candidate) => candidate.name === name);
  if (!entry) throw new Error("Missing synthetic catalog fixture.");
  return entry;
}

